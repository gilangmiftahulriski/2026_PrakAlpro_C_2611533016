# Nama variabel ditambah 4 digit nim terakhir contoh: angka_3016
# Program ini menggunakan fungsi input()
# Nilai yang dimasukkan akan dikonversi menjadi tipe data integer
# Progarm operator perbandingan dalam python

angka1_3016 = int(input("Input angka-1: "))
angka2_3016 = int(input("Input angka-2: "))

# Lebih besar dari
hasil_3016 = angka1_3016 > angka2_3016
print("\nOperator Lebih Besar Dari")
print("angka1 > angka2 =", hasil_3016)

# Lebih kecil dari
hasil_3016 = angka1_3016 < angka2_3016  
print("\nOperator Lebih Kecil Dari")
print("angka1 < angka2 =", hasil_3016)

# Lebih besar dari sama dengan
hasil_3016 = angka1_3016 >= angka2_3016
print("\nOperator Lebih Besar Dari atau Sama Dengan")
print("angka1 >= angka2 =", hasil_3016)

# Lebih kecil dari sama dengan  
hasil_3016 = angka1_3016 <= angka2_3016
print("\nOperator Lebih Kecil Dari atau Sama Dengan")
print("angka1 <= angka2 =", hasil_3016)

# Sama dengan
hasil_3016 = angka1_3016 == angka2_3016
print("\nOperator Sama Dengan")
print("angka1 == angka2 =", hasil_3016)

# Tidak sama dengan
hasil_3016 = angka1_3016 != angka2_3016
print("\nOperator Tidak Sama Dengan")
print("angka1 != angka2 =", hasil_3016)

# Tambahan perbandingan berantai dalam Python
hasil_3016 = 0 < angka1_3016 < 100
